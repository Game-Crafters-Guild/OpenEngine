#pragma once

#include "Mathematics/RectInt.h"

#include <cstdint>
#include <array>
#include <functional>
#include <memory>
#include <optional>
#include <string>
#include <vector>

namespace GameEngine
{
namespace Platform
{
class Window;
}
class INativeContextMenu;

/// The platform chooses the native menu bar, an integrated caption, or a client menu row.
enum class ToolbarPresentation : uint8_t { NativeMenuBar, WindowTitleBar, ClientMenuBar };

/// Native menu identity and label, in display order.
struct ToolbarMenu
{
    uint32_t Id;
    std::string Title;
};

/// A menu heading's rectangle in physical client pixels. Id 0 opens all menus.
struct TitleBarMenuRegion
{
    uint32_t Id = 0;
    Mathematics::RectInt Bounds;
    bool operator==(const TitleBarMenuRegion&) const = default;
};

enum class TitleBarButton : uint8_t { None, Minimize, Maximize, Close };

/// Caption button bounds in physical client pixels, shared by painting and hit testing.
struct TitleBarButtonRegion
{
    TitleBarButton Button = TitleBarButton::None;
    Mathematics::RectInt Bounds;
    bool operator==(const TitleBarButtonRegion&) const = default;
};

struct TitleBarMetrics
{
    int Height = 0;
    int CaptionWidth = 0;
    std::array<TitleBarButtonRegion, 3> Buttons{};
    TitleBarButton HoveredButton = TitleBarButton::None;
    bool Maximized = false;
    bool operator==(const TitleBarMetrics&) const = default;
};

// Cross-platform native menu/toolbar interface
class INativeToolbar
{
  public:
    using CommandCallback = std::function<void(uint32_t)>;
    using MenuFactory = std::function<std::unique_ptr<INativeContextMenu>()>;
    virtual ~INativeToolbar() = default;

    /// Attaches to a platform window and creates the menu backend. A WindowTitleBar
    /// presentation also installs its custom frame here, before the first SetTitleBarLayout.
    virtual bool Install(Platform::Window* window) = 0;
    // Remove the menu and restore any hooks/resources
    virtual void Uninstall() = 0;

    // Remove all menus and rebuild the empty menu bar
    virtual void Clear() = 0;

    // Register a handler for command IDs generated by AddItem(...)
    virtual void SetCommandHandler(CommandCallback cb) = 0;
    /// The host supplies its popup implementation for a client-rendered menu bar.
    virtual void SetMenuFactory(MenuFactory /*factory*/) {}
    /// Returns true when the command is placed in the native application menu.
    virtual bool SetApplicationQuitCommand(uint32_t /*commandId*/) { return false; }

    // Menu building API (UTF-8 titles)
    // Returns menu IDs that can be used as parents for submenus/items
    virtual uint32_t AddMenu(const std::string& title) = 0;
    virtual uint32_t AddSubMenu(uint32_t parentMenuId, const std::string& title) = 0;
    virtual void AddItem(uint32_t parentMenuId, const std::string& title, uint32_t commandId) = 0;
    /// Appends a separator line after the last entry of the menu.
    virtual void AddSeparator(uint32_t parentMenuId) = 0;

    // Optional: assign an image to an existing command item. Paths use the
    // same asset aliases as native context-menu icons (for example editor:Icons/foo.png).
    virtual void SetItemIcon(uint32_t /*commandId*/, const std::string& /*imagePath*/) {}

    // Optional: update the title for an existing item identified by commandId.
    // Default implementation is a no-op so platforms that do not support
    // in-place relabeling can ignore this while still compiling.
    virtual void UpdateItemTitle(uint32_t /*commandId*/, const std::string& /*title*/) {}

    virtual ToolbarPresentation GetPresentation() const { return ToolbarPresentation::NativeMenuBar; }
    virtual std::vector<ToolbarMenu> GetMenus() const { return {}; }
    virtual uint64_t GetMenuRevision() const { return 0; }
    virtual TitleBarMetrics GetTitleBarMetrics() const { return {}; }
    /// Height 0 suspends the custom frame (fullscreen); menus remain detached.
    /// Called on the window's UI thread.
    virtual void SetTitleBarLayout(int /*height*/, std::vector<TitleBarMenuRegion> /*regions*/) {}
    /// Opens a dropdown at its heading, or the complete menu tree for id 0.
    virtual void ShowTitleBarMenu(uint32_t /*menuId*/) {}
    /// The heading whose dropdown is open: its menu id, 0 for the complete tree, empty when none is open.
    virtual std::optional<uint32_t> GetOpenMenu() const { return std::nullopt; }
};

// Factory: returns the platform's toolbar presentation.
std::unique_ptr<INativeToolbar> CreateNativeToolbar();

} // namespace GameEngine
