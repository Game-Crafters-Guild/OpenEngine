#include "ComponentMirror.h"

#include "BindingRules.h"
#include "Lexical.h"

#include <algorithm>

namespace GameEngine::ComponentScanner
{

bool HasMirror(ComponentClass componentClass)
{
    return componentClass == ComponentClass::GameData || componentClass == ComponentClass::EngineOwned ||
           componentClass == ComponentClass::Element;
}

std::string_view ComponentClassText(ComponentClass componentClass)
{
    switch (componentClass)
    {
    case ComponentClass::GameData: return "game data, a full mirror";
    case ComponentClass::EngineOwned: return "engine-owned, a readonly mirror (@ge-readonly)";
    case ComponentClass::EngineInternal: return "engine-internal, no mirror (@ge-engine-internal)";
    case ComponentClass::EditorOnly: return "editor-only, no mirror (@ge-editor-only)";
    case ComponentClass::Element: return "element struct, mirrored inside its owner";
    }
    return {};
}

std::string ComponentClassesText(const ComponentMirrors& mirrors)
{
    std::vector<const MirrorStruct*> sorted;
    for (const MirrorStruct& mirror : mirrors.Structs)
        sorted.push_back(&mirror);
    std::sort(sorted.begin(), sorted.end(), [](const MirrorStruct* a, const MirrorStruct* b)
              { return a->Name != b->Name ? a->Name < b->Name : a->CppName < b->CppName; });
    std::string text = "# The class of every reflected component: what its C# mirror is (Tools/ComponentScanner/ComponentMirror.h).\n"
                       "# Generated by ComponentScanner; do not edit.\n";
    for (const MirrorStruct* mirror : sorted)
        text += mirror->Name + ": " + std::string(ComponentClassText(mirror->Class)) + "\n";
    return text;
}

std::string MirrorCSharpFile(std::string_view header)
{
    constexpr std::string_view kComponents = "Components/";
    if (Lexical::StartsWith(header, kComponents))
        header.remove_prefix(kComponents.size());
    const std::size_t dot = header.rfind('.');
    const std::size_t slash = header.rfind('/');
    if (dot != std::string_view::npos && (slash == std::string_view::npos || dot > slash))
        header = header.substr(0, dot);
    return std::string(header) + ".g.cs";
}

std::string MirrorMemberName(std::string_view fieldName)
{
    return BindingRules::CSharpField(fieldName);
}

std::string MirrorArrayType(std::string_view fieldName)
{
    return MirrorMemberName(fieldName) + "Array";
}

} // namespace GameEngine::ComponentScanner
