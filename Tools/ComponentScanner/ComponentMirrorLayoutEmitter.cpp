#include "ComponentMirrorLayoutEmitter.h"

#include "BindingRules.h"

#include <cstdint>
#include <set>

namespace GameEngine::ComponentScanner::ComponentMirrorLayoutEmitter
{
namespace
{

// A C++ literal of an enumerator's value, of the type the value asserts compare against (long long).
std::string EnumLiteral(std::int64_t value)
{
    if (value == INT64_MIN)
        return "(-9223372036854775807ll - 1)";
    return std::to_string(value) + "ll";
}

} // namespace

std::string Emit(const ComponentMirrors& mirrors)
{
    std::set<std::string> headers;
    for (const MirrorStruct& mirror : mirrors.Structs)
        if (HasMirror(mirror.Class))
            headers.insert(mirror.Header);
    for (const MirrorEnum& e : mirrors.Enums)
        if (!e.Bound)
            headers.insert(e.Header);

    std::string out = "// <auto-generated>\n// Generated by ComponentScanner from the component headers; do not edit. It pins the\n"
                      "// layout of every C# component mirror to the compiler's (Tools/ComponentScanner/ComponentMirror.h).\n"
                      "// </auto-generated>\n";
    for (const std::string& header : headers)
        out += "#include \"" + header + "\"\n";
    out += "\n#include <cstddef>\n#include <cstdint>\n#include <type_traits>\n\n";

    for (const MirrorEnum& e : mirrors.Enums)
    {
        if (e.Bound)
            continue;
        out += "static_assert(std::is_same_v<std::underlying_type_t<" + e.CppName + ">, " +
               BindingRules::NativeValueType(ApiType{e.Underlying, {}, {}}, BindingRules::Index{}) + ">, \"" + e.Name +
               ": the underlying type differs from the mirror\");\n";
        for (const ApiEnumValue& value : e.Values)
            out += "static_assert(static_cast<long long>(" + e.CppName + "::" + value.Name + ") == " + EnumLiteral(value.Value) +
                   ", \"" + e.Name + "::" + value.Name + ": the value differs from the mirror\");\n";
    }
    for (const MirrorStruct& mirror : mirrors.Structs)
    {
        if (!HasMirror(mirror.Class))
            continue;
        out += "static_assert(sizeof(" + mirror.CppName + ") == " + std::to_string(mirror.Size) + ", \"" + mirror.Name +
               ": the size differs from the mirror\");\n";
        out += "static_assert(alignof(" + mirror.CppName + ") == " + std::to_string(mirror.Align) + ", \"" + mirror.Name +
               ": the alignment differs from the mirror\");\n";
        for (const MirrorField& field : mirror.Fields)
        {
            const std::string label = mirror.Name + "." + field.Name;
            out += "static_assert(offsetof(" + mirror.CppName + ", " + field.Name + ") == " + std::to_string(field.Offset) + ", \"" +
                   label + ": the offset differs from the mirror\");\n";
            out += "static_assert(sizeof(" + mirror.CppName + "::" + field.Name + ") == " + std::to_string(field.Size) + ", \"" +
                   label + ": the size differs from the mirror\");\n";
        }
    }
    return out;
}

} // namespace GameEngine::ComponentScanner::ComponentMirrorLayoutEmitter
